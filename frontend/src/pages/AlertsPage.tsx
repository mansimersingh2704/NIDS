import React, { useEffect, useState } from 'react';
import {
  ShieldAlert,
  Search,
  Filter,
  Eye,
  ChevronLeft,
  ChevronRight,
  X,
  FileCode,
  Activity,
} from 'lucide-react';
import { api } from '../services/api';
import { AlertItem } from '../types/nids';

export const AlertsPage: React.FC = () => {
  const [alerts, setAlerts] = useState<AlertItem[]>([]);
  const [total, setTotal] = useState<number>(0);
  const [page, setPage] = useState<number>(1);
  const [limit] = useState<number>(15);
  const [severityFilter, setSeverityFilter] = useState<string>('');
  const [ipFilter, setIpFilter] = useState<string>('');
  const [attackFilter, setAttackFilter] = useState<string>('');
  const [loading, setLoading] = useState<boolean>(true);
  const [selectedAlert, setSelectedAlert] = useState<AlertItem | null>(null);

  const fetchAlerts = () => {
    setLoading(true);
    api.getAlerts({
      page,
      limit,
      severity: severityFilter || undefined,
      attack_type: attackFilter || undefined,
      ip: ipFilter || undefined,
    })
      .then((res) => {
        setAlerts(res.data.alerts);
        setTotal(res.data.total);
      })
      .catch((err) => console.error('Error fetching alerts:', err))
      .finally(() => setLoading(false));
  };

  useEffect(() => {
    fetchAlerts();
  }, [page, severityFilter, attackFilter, ipFilter]);

  const totalPages = Math.max(1, Math.ceil(total / limit));

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-2 border-b border-navy-700/60">
        <div>
          <h1 className="text-xl font-bold text-slate-100 tracking-tight">SOC Alert Management</h1>
          <p className="text-xs text-slate-400 mt-0.5">
            Deduplicated threat events generated by machine learning inference and heuristic boundary validation.
          </p>
        </div>
        <div className="mt-2 sm:mt-0 text-xs font-mono text-slate-400">
          Total Alerts: <span className="text-slate-100 font-semibold">{total}</span>
        </div>
      </div>

      {/* Filter and Search Bar */}
      <div className="p-4 rounded-xl bg-navy-850 border border-navy-700/80 grid grid-cols-1 sm:grid-cols-3 gap-3">
        {/* IP Search */}
        <div className="relative">
          <Search className="w-4 h-4 text-slate-400 absolute left-3 top-2.5" />
          <input
            type="text"
            placeholder="Search Source or Dest IP..."
            value={ipFilter}
            onChange={(e) => {
              setIpFilter(e.target.value);
              setPage(1);
            }}
            className="w-full bg-navy-900 border border-navy-700 rounded-lg pl-9 pr-3 py-2 text-xs font-mono text-slate-200 placeholder-slate-500 focus:outline-none focus:border-blue-500"
          />
        </div>

        {/* Severity Filter */}
        <div className="relative">
          <Filter className="w-4 h-4 text-slate-400 absolute left-3 top-2.5" />
          <select
            value={severityFilter}
            onChange={(e) => {
              setSeverityFilter(e.target.value);
              setPage(1);
            }}
            className="w-full bg-navy-900 border border-navy-700 rounded-lg pl-9 pr-3 py-2 text-xs font-mono text-slate-200 focus:outline-none focus:border-blue-500"
          >
            <option value="">All Severity Levels</option>
            <option value="Critical">Critical</option>
            <option value="High">High</option>
            <option value="Medium">Medium</option>
            <option value="Low">Low</option>
          </select>
        </div>

        {/* Attack Category Filter */}
        <div className="relative">
          <input
            type="text"
            placeholder="Filter by Attack Category (e.g. DDoS, PortScan)..."
            value={attackFilter}
            onChange={(e) => {
              setAttackFilter(e.target.value);
              setPage(1);
            }}
            className="w-full bg-navy-900 border border-navy-700 rounded-lg px-3 py-2 text-xs font-mono text-slate-200 placeholder-slate-500 focus:outline-none focus:border-blue-500"
          />
        </div>
      </div>

      {/* Alerts Table */}
      <div className="p-5 rounded-xl bg-navy-850 border border-navy-700/80">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs font-mono">
            <thead className="bg-navy-900 text-slate-400 uppercase text-[10px] tracking-wider border-b border-navy-700">
              <tr>
                <th className="py-2.5 px-3">Alert ID</th>
                <th className="py-2.5 px-3">Timestamp</th>
                <th className="py-2.5 px-3">Source IP</th>
                <th className="py-2.5 px-3">Destination IP</th>
                <th className="py-2.5 px-3">Proto</th>
                <th className="py-2.5 px-3">Attack Category</th>
                <th className="py-2.5 px-3">Severity</th>
                <th className="py-2.5 px-3">Confidence</th>
                <th className="py-2.5 px-3">Occurrences</th>
                <th className="py-2.5 px-3 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-navy-700/50">
              {loading ? (
                <tr>
                  <td colSpan={10} className="py-12 text-center text-slate-400">
                    <Activity className="w-5 h-5 animate-spin mx-auto mb-2 text-blue-400" />
                    Loading security alerts...
                  </td>
                </tr>
              ) : alerts.length > 0 ? (
                alerts.map((alt) => (
                  <tr key={alt.alert_id} className="hover:bg-navy-800/40 transition-colors">
                    <td className="py-2.5 px-3 font-semibold text-slate-200">{alt.alert_id}</td>
                    <td className="py-2.5 px-3 text-slate-400">
                      {alt.timestamp ? new Date(alt.timestamp).toLocaleTimeString() : 'N/A'}
                    </td>
                    <td className="py-2.5 px-3 text-slate-200">{alt.source_ip}:{alt.source_port}</td>
                    <td className="py-2.5 px-3 text-slate-200">{alt.destination_ip}:{alt.destination_port}</td>
                    <td className="py-2.5 px-3 text-slate-400">
                      {alt.protocol === 6 ? 'TCP' : alt.protocol === 17 ? 'UDP' : `P-${alt.protocol}`}
                    </td>
                    <td className="py-2.5 px-3 font-bold text-rose-400">{alt.attack_type}</td>
                    <td className="py-2.5 px-3">
                      <span className={`px-2 py-0.5 rounded text-[10px] font-bold uppercase ${
                        alt.severity === 'Critical' ? 'bg-rose-500/20 text-rose-400 border border-rose-500/30' :
                        alt.severity === 'High' ? 'bg-amber-500/20 text-amber-400 border border-amber-500/30' :
                        alt.severity === 'Medium' ? 'bg-yellow-500/20 text-yellow-400 border border-yellow-500/30' :
                        'bg-emerald-500/20 text-emerald-400 border border-emerald-500/30'
                      }`}>
                        {alt.severity}
                      </span>
                    </td>
                    <td className="py-2.5 px-3 text-slate-300">{(alt.confidence * 100).toFixed(1)}%</td>
                    <td className="py-2.5 px-3 text-slate-400">
                      <span className="px-2 py-0.5 rounded bg-navy-900 border border-navy-700 font-bold">
                        {alt.occurrence_count}
                      </span>
                    </td>
                    <td className="py-2.5 px-3 text-right">
                      <button
                        onClick={() => setSelectedAlert(alt)}
                        className="px-2.5 py-1 rounded bg-navy-800 hover:bg-navy-700 text-blue-400 text-xs font-semibold inline-flex items-center space-x-1 border border-navy-700 transition-colors"
                      >
                        <Eye className="w-3.5 h-3.5" />
                        <span>Evidence</span>
                      </button>
                    </td>
                  </tr>
                ))
              ) : (
                <tr>
                  <td colSpan={10} className="py-12 text-center text-slate-500 font-mono text-xs">
                    No alerts matching the selected filters.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        {/* Pagination Bar */}
        <div className="flex items-center justify-between pt-4 mt-2 border-t border-navy-700/60 text-xs font-mono">
          <span className="text-slate-400">
            Page {page} of {totalPages} ({total} alerts)
          </span>
          <div className="flex items-center space-x-2">
            <button
              onClick={() => setPage((p) => Math.max(1, p - 1))}
              disabled={page <= 1}
              className="p-1.5 rounded bg-navy-900 border border-navy-700 text-slate-300 hover:bg-navy-800 disabled:opacity-40"
            >
              <ChevronLeft className="w-4 h-4" />
            </button>
            <button
              onClick={() => setPage((p) => Math.min(totalPages, p + 1))}
              disabled={page >= totalPages}
              className="p-1.5 rounded bg-navy-900 border border-navy-700 text-slate-300 hover:bg-navy-800 disabled:opacity-40"
            >
              <ChevronRight className="w-4 h-4" />
            </button>
          </div>
        </div>
      </div>

      {/* Evidence Forensic Modal */}
      {selectedAlert && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-sm">
          <div className="bg-navy-900 border border-navy-700 rounded-xl max-w-2xl w-full max-h-[85vh] flex flex-col shadow-2xl">
            {/* Modal Header */}
            <div className="p-4 border-b border-navy-700 flex items-center justify-between">
              <div className="flex items-center space-x-2">
                <FileCode className="w-4 h-4 text-blue-400" />
                <h3 className="text-sm font-bold text-slate-100 font-mono">
                  Forensic Evidence: {selectedAlert.alert_id}
                </h3>
              </div>
              <button
                onClick={() => setSelectedAlert(null)}
                className="p-1 rounded text-slate-400 hover:text-slate-200 hover:bg-navy-800"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            {/* Modal Content */}
            <div className="p-5 overflow-y-auto space-y-4 font-mono text-xs">
              <div className="grid grid-cols-2 gap-3 p-3 bg-navy-850 rounded-lg border border-navy-700">
                <div>
                  <span className="text-slate-400 text-[11px] block">Threat Signature</span>
                  <span className="text-rose-400 font-bold text-sm">{selectedAlert.attack_type}</span>
                </div>
                <div>
                  <span className="text-slate-400 text-[11px] block">Severity / Confidence</span>
                  <span className="text-slate-200 font-semibold text-sm">
                    {selectedAlert.severity} ({(selectedAlert.confidence * 100).toFixed(1)}%)
                  </span>
                </div>
                <div>
                  <span className="text-slate-400 text-[11px] block">Directional Source</span>
                  <span className="text-slate-200">{selectedAlert.source_ip}:{selectedAlert.source_port}</span>
                </div>
                <div>
                  <span className="text-slate-400 text-[11px] block">Directional Target</span>
                  <span className="text-slate-200">{selectedAlert.destination_ip}:{selectedAlert.destination_port}</span>
                </div>
              </div>

              {/* Multi-Class Probability Distribution */}
              {selectedAlert.evidence?.detection_probabilities && (
                <div>
                  <span className="text-slate-300 font-semibold block mb-1.5">Model Probability Vector:</span>
                  <div className="grid grid-cols-3 gap-2">
                    {Object.entries(selectedAlert.evidence.detection_probabilities).map(([cls, prob]) => (
                      <div key={cls} className="p-2 rounded bg-navy-850 border border-navy-700">
                        <span className="text-slate-400 text-[10px] block">{cls}</span>
                        <span className="text-slate-200 font-bold">{((prob as number) * 100).toFixed(1)}%</span>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Raw Flow Feature Vector */}
              <div>
                <span className="text-slate-300 font-semibold block mb-1.5">Directional Flow Features:</span>
                <pre className="p-3 rounded-lg bg-navy-950 border border-navy-800 text-[11px] text-slate-300 overflow-x-auto">
                  {JSON.stringify(selectedAlert.evidence?.flow_features || {}, null, 2)}
                </pre>
              </div>
            </div>

            {/* Modal Footer */}
            <div className="p-4 border-t border-navy-700 flex justify-end">
              <button
                onClick={() => setSelectedAlert(null)}
                className="px-4 py-1.5 rounded-lg bg-navy-800 hover:bg-navy-700 text-slate-200 text-xs font-semibold"
              >
                Close Evidence
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
